export const DOMESTIC_PLACEMENT_BY_CHANNEL = RAW_PLACEMENT_BY_CHANNEL;

export const DOMESTIC_PLACEMENT_LABEL_MAP = (() => {
  const m = {};
  Object.values(RAW_PLACEMENT_BY_CHANNEL).forEach((items) => {
    items.forEach((item) => {
      if (!m[item.key]) m[item.key] = item.zh;
    });
  });
  return m;
})();

function toChannelIds(channelMediaValues) {
  const values = Array.isArray(channelMediaValues) ? channelMediaValues : channelMediaValues ? [channelMediaValues] : [];
  const ids = new Set();
  values.forEach((value) => {
    String(value)
      .split(',')
      .map((x) => x.trim())
      .filter(Boolean)
      .forEach((id) => ids.add(id));
  });
  return Array.from(ids);
}

export function getDomesticPlacementOptionsByChannelMedia(channelMediaValues) {
  const selectedIds = toChannelIds(channelMediaValues);
  const sourceIds = selectedIds.length > 0 ? selectedIds : Object.keys(RAW_PLACEMENT_BY_CHANNEL);
  const merged = new Map();
  sourceIds.forEach((id) => {
    const list = RAW_PLACEMENT_BY_CHANNEL[id] || [];
    list.forEach((item) => {
      if (!item?.key || !item?.zh) return;
      if (!merged.has(item.key)) merged.set(item.key, item.zh);
    });
  });
  return Array.from(merged.entries())
    .sort((a, b) => Number(a[0]) - Number(b[0]))
    .map(([value, label]) => ({ value, label }));
}
